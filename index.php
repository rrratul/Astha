        if ('webkitSpeechRecognition' in window) {
            recognition = new webkitSpeechRecognition();
            recognition.continuous = false;
            recognition.interimResults = false;
            recognition.lang = 'en-US';
            
            // Recognition started
            recognition.onstart = function() {
                recognitionActive = true;
                voiceAssistantBtn.classList.add('listening');
                voiceFeedback.style.display = 'block';
                voiceResult.textContent = 'Listening...';
            };
            
            // Results received
            recognition.onresult = function(event) {
                let transcript = '';
                if (event.results && event.results.length > 0) {
                    transcript = event.results[0][0].transcript;
                    voiceResult.textContent = transcript;
                    processVoiceCommand(transcript.toLowerCase().trim());
                } else {
                    voiceResult.textContent = 'Sorry, I didn\'t catch that.';
                    speakResponse("Sorry, I didn't catch that. Please try again.");
                }
            };
            
            // Recognition ended
            recognition.onend = function() {
                recognitionActive = false;
                voiceAssistantBtn.classList.remove('listening');
                setTimeout(function() {
                    voiceFeedback.style.display = 'none';
                }, 1000);
            };
            
            // Error handling
            recognition.onerror = function(event) {
                recognitionActive = false;
                voiceAssistantBtn.classList.remove('listening');
                console.error("Speech recognition error:", event.error);
                
                let errorMessage = "There was a problem with voice recognition";
                switch(event.error) {
                    case 'network':
                        errorMessage = "Network error occurred. Please check your connection.";
                        break;
                    case 'not-allowed':
                    case 'service-not-allowed':
                        errorMessage = "Microphone access is not allowed. Please enable it in your browser settings.";
                        break;
                    case 'aborted':
                        errorMessage = "Recognition was aborted.";
                        break;
                    case 'no-speech':
                        errorMessage = "No speech was detected. Please try again.";
                        break;
                    case 'audio-capture':
                        errorMessage = "Could not capture audio. Please check your microphone.";
                        break;
                }
                
                voiceResult.textContent = 'Error: ' + errorMessage;
                speakResponse(errorMessage);
                
                setTimeout(function() {
                    voiceFeedback.style.display = 'none';
                }, 3000);
            };
            
            return true;
        } else {
            alert("Voice recognition is not supported in your browser. Try using Chrome for best experience.");
            return false;
        }
    }
    
